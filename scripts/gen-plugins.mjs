#!/usr/bin/env node
// Scans plugins/*/index.ts and writes lib/plugins/manifest.generated.ts (static imports, so Next.js can bundle them).
// Runs automatically before `npm run dev` and `npm run build`; run `npm run plugins` after adding one if the dev server is already up.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export function scanPlugins(pluginsDir) {
  if (!fs.existsSync(pluginsDir)) return [];
  return fs.readdirSync(pluginsDir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith("_") && !d.name.startsWith(".") && d.name !== "node_modules")
    .filter((d) => fs.existsSync(path.join(pluginsDir, d.name, "index.ts")))
    .map((d) => d.name)
    .sort();
}

export function renderManifest(dirs) {
  const imports = dirs.map((d, i) => `import p${i} from ${JSON.stringify(`../../plugins/${d}/index.ts`)};`);
  const items = dirs.map((d, i) => `  { dir: ${JSON.stringify(d)}, plugin: p${i} },`);
  return [
    "// AUTO-GENERATED by scripts/gen-plugins.mjs from plugins/*/index.ts. Do not edit by hand.",
    "// Regenerate with: npm run plugins",
    ...imports,
    "",
    "export const PLUGINS: { dir: string; plugin: unknown }[] = [",
    ...items,
    "];",
    "",
  ].join("\n");
}

function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const out = path.join(root, "lib", "plugins", "manifest.generated.ts");
  const dirs = scanPlugins(path.join(root, "plugins"));
  const next = renderManifest(dirs);
  const prev = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (prev !== next) fs.writeFileSync(out, next);   // untouched when unchanged, so dev reloads don't loop
  console.log(`plugins: ${dirs.length ? dirs.join(", ") : "(none)"}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
